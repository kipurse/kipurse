// Keys are the original Chinese strings; interpolated strings match "%@" templates at runtime.
import Foundation
public enum Loc {
  /// "zh" / "en": what server pages and error messages should render in (single language, follows the iPhone).
  public static var code: String { isChinese ? "zh" : "en" }
  /// Adds `lang=zh|en` to Kipurse server pages (kipurse.com or the configured servers); other sites untouched.
  public static func withLang(_ u: URL, servers: [String] = Loc.servers) -> URL {
    guard let h = u.host?.lowercased(), u.scheme?.hasPrefix("http") == true,
          h == "kipurse.com" || h.hasSuffix(".kipurse.com") || servers.contains(where: { URL(string: $0)?.host?.lowercased() == h }),
          var c = URLComponents(url: u, resolvingAgainstBaseURL: false) else { return u }
    var q = (c.queryItems ?? []).filter { $0.name != "lang" }; q.append(URLQueryItem(name: "lang", value: code)); c.queryItems = q
    return c.url ?? u
  }
  public static var servers: [String] { ["KipurseServer", "KipurseMainnetServer"].compactMap { Bundle.main.object(forInfoDictionaryKey: $0) as? String } }
  /// Tests only: the "kp.lang.test" default (unit tests) or a "-kp.lang zh|en" launch argument (UI tests / screenshots).
  /// A value saved by the old in-app language picker is ignored: the app always follows the iPhone language (owner rule).
  public static var override: String? {
    get {
      if let t = UserDefaults.standard.string(forKey: "kp.lang.test") { return t }
      let a = CommandLine.arguments; if let i = a.firstIndex(of: "-kp.lang"), i + 1 < a.count, ["zh", "en"].contains(a[i + 1]) { return a[i + 1] }
      return nil
    }
    set { UserDefaults.standard.set(newValue, forKey: "kp.lang.test") }
  }
  public static var isChinese: Bool { if let o = override { return o == "zh" }; return (Locale.preferredLanguages.first ?? "en").lowercased().hasPrefix("zh") }
